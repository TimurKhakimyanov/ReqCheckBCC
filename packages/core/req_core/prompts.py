def segment_prompt(fragment: str, candidates: list[str], limit: int) -> str:
    cand = "\n".join(f"- {c}" for c in candidates) or "- (нет)"
    return f"{SEGMENT_TASK}\n\nКандидаты:\n{cand}\n\n{doc_block(fragment, limit)}"


