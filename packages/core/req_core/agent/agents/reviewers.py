BY_KEY = {p["key"]: p for p in PERSPECTIVES}


def doc_parts(ctx: Ctx) -> list[tuple[int, int]]:
    """Части документа для ревью набора. Обычно одна; большой документ делится так, чтобы
    часть вместе со списком требований помещалась в окно модели."""
    if "_review_parts" not in ctx.meta:
        # место под документ = лимит запроса − самые длинные инструкции рецензента − список требований − подсказки
        longest = max(PERSPECTIVES, key=lambda p: len(p["focus"]) + len(p["persona"]))
        system, user0 = prompts.load("reviewer").render(
            persona=longest["persona"], focus=longest["focus"], document="", requirements="", hints="",
            criteria=criteria_block([BY_CODE[c] for c in ("S1", "S4", "S6", "S7")]),
        )
        room = ctx.room(system, user0) - _table_cap(ctx) - _hints_cap(ctx)
        if room < 600:
            raise Stop(LLMConfigError(
                f"Окно модели слишком мало для работы агента: {ctx.budget.window} токенов. "
                "Нужно не меньше ~8000. Выберите модель с большим окном или уменьшите max_output_tokens провайдера."
            ))
        parts = split_doc(ctx, room)
        ctx.meta["_review_parts"] = parts
        ctx.meta.setdefault("context_mode", {}).update({"review_parts": len(parts), "doc_fits": len(parts) == 1})
    return ctx.meta["_review_parts"]


def _table_cap(ctx: Ctx) -> int:
    return ctx.room() // 5


def _hints_cap(ctx: Ctx) -> int:
    return min(12_000, ctx.room() // 10)


def review(ctx: Ctx, intent_id: str, key: str, part: int = 0) -> None:
    persp = BY_KEY[key]
    crits = [BY_CODE[c] for c in persp["codes"]]
    parts = doc_parts(ctx)
    a, b = parts[part]
    whole = len(parts) == 1
    if whole:
        document, hints = ctx.doc_text, hints_text(ctx, max_chars=_hints_cap(ctx))
        table = req_table(ctx, max_chars=_table_cap(ctx))
    else:
        # Документ не помещается в окно: рецензент видит часть текста и краткий список требований остальных частей.
        document = (
            f"[Документ велик и проверяется по частям. Перед тобой часть {part + 1} из {len(parts)}: {ctx.doc.place(a, b)}. "
            "Остальные части представлены списком требований ниже — используй его для поиска противоречий и пропусков между частями.]\n"
            + ctx.doc.numbered(a, b)
        )
        hints = hints_text(ctx, a, b, max_chars=_hints_cap(ctx))
        table = req_table(ctx, span=(a, b), max_chars=_table_cap(ctx))
    system, user = prompts.load("reviewer").render(
        persona=persp["persona"], focus=persp["focus"], criteria=criteria_block(crits),
        document=document, requirements=table, hints=hints,
    )
    label = persp["title"] + ("" if whole else f" · часть {part + 1}/{len(parts)}")
    data = ctx.llm.json("reviewer", system, user, label=label, prompt="reviewer")
    if not isinstance(data, dict):
        raise ValueError("рецензент вернул не объект")

    verdicts = data.get("verdicts") if isinstance(data.get("verdicts"), dict) else {}
    store = ctx.meta.setdefault("set_verdicts", {})
    for code in persp["codes"]:
        v = verdicts.get(code)
        status, rationale = "", ""
        if isinstance(v, dict):
            status, rationale = s(v.get("status")).lower(), s(v.get("rationale"))
        elif isinstance(v, str):
            status = v.lower()
        if status in ("ok", "violation"):
            store.setdefault(code, []).append({"by": persp["title"], "status": status, "rationale": rationale})

    n = 0
    for f in lst(data.get("findings")):
        if not isinstance(f, dict):
            continue
        code = s(f.get("criterion")).upper()
        if code not in BY_CODE or not code.startswith("S"):
            f["criterion"] = persp["codes"][0]
        req_ids = [s(r) for r in lst(f.get("req_ids")) if s(r)]
        node = record_finding(
            ctx, source=f"reviewer:{key}", level="set", raw=f, req_ids=req_ids,
            evidence_raw=[e for e in lst(f.get("evidence")) if isinstance(e, dict)], intent=intent_id,
        )
        if node is not None:
            n += 1
    ctx.graph.get(intent_id).payload["findings"] = n
